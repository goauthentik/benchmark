import http from "k6/http";
import { check, fail } from "k6";
import { SharedArray } from "k6/data";

const host = __ENV.BENCH_HOST ? __ENV.BENCH_HOST : "localhost";
const port = __ENV.BENCH_PORT ? __ENV.BENCH_PORT : 9000;
const VUs = __ENV.VUS ? __ENV.VUS : 8;
const usersFile = __ENV.USERS_FILE ? __ENV.USERS_FILE : "./users.json";

const profile = __ENV.PROFILE ? __ENV.PROFILE : "quick";
const quickDuration = __ENV.QUICK_DURATION ? Number(__ENV.QUICK_DURATION) : 150;
// k6 has no infinite duration, so the burn profile runs for a year and is
// expected to be stopped by stopping its container.
const burnDuration = __ENV.BURN_DURATION ? __ENV.BURN_DURATION : "8760h";
const scenarioGap = 15;

// Scenarios select their authentication flow by slug instead of by brand, so a
// single hostname is enough - no per-scenario DNS records needed.
const flows = {
    "no-mfa": __ENV.FLOW_NO_MFA ? __ENV.FLOW_NO_MFA : "default-authentication-flow",
    "with-mfa": __ENV.FLOW_WITH_MFA ? __ENV.FLOW_WITH_MFA : "default-authentication-mfa-flow",
};

const profiles = {
    // Each scenario gets a fixed window, one after the other, then k6 exits.
    quick: (index) => ({
        executor: "constant-vus",
        vus: VUs,
        duration: `${quickDuration}s`,
        startTime: `${(quickDuration + scenarioGap) * index}s`,
    }),
    // All scenarios run side by side for as long as the container is up.
    burn: () => ({
        executor: "constant-vus",
        vus: VUs,
        duration: burnDuration,
    }),
};

if (!profiles[profile]) {
    throw new Error(`Unknown PROFILE "${profile}", expected one of: ${Object.keys(profiles).join(", ")}`);
}

// Credentials generated by gen-blueprint.py alongside the test-data blueprint.
// SharedArray keeps a single copy in memory regardless of VU count.
const users = new SharedArray("users", () => JSON.parse(open(usersFile)));

export const options = {
    scenarios: Object.fromEntries(
        Object.keys(flows).map((name, i) => [
            name,
            {
                ...profiles[profile](i),
                env: {
                    FLOW: flows[name],
                },
                tags: {
                    testid: `login-${name}`,
                    profile: profile,
                },
            },
        ]),
    ),
};

export default function () {
    const flow = __ENV.FLOW;
    const url = http.url`http://${host}:${port}/api/v3/flows/executor/${flow}/`;
    const cookieJar = new http.CookieJar();
    const params = {
        jar: cookieJar,
        headers: {
            "Content-Type": "application/json",
            Accept: "*/*",
        },
    };
    // Walk the user list so concurrent VUs never authenticate as the same user.
    const user = users[(__VU - 1 + __ITER * VUs) % users.length];
    let res = http.get(url, params);
    let i = 0;
    let completed = false;
    while (true) {
        if (i > 10) {
            fail("Test made more than 10 queries.");
            break;
        }
        check(res, {
            "status is 200": (res) => res.status === 200,
        });
        if (res.status !== 200) {
            fail("Endpoint did not return 200.");
            break;
        }

        const component = res.json()["component"];
        let payload = {};
        if (component === "ak-stage-identification") {
            payload = {
                uid_field: user.username,
            };
        } else if (component === "ak-stage-password") {
            payload = {
                password: user.password,
            };
        } else if (component === "ak-stage-authenticator-validate") {
            payload = {
                code: "staticToken",
            };
        } else if (component === "xak-flow-redirect") {
            completed = true;
            break;
        } else {
            console.log(`Unknown component type: ${component}`);
            break;
        }

        payload["component"] = component;
        res = http.post(url, JSON.stringify(payload), params);
        i++;
    }
    check(completed, {
        "login completed": (completed) => completed,
    });
}
